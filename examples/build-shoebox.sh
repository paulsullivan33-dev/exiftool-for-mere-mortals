#!/bin/sh
# build-shoebox.sh — build the specimen shoebox for
# "ExifTool for Mere Mortals".
#
# Usage:  sh build-shoebox.sh [directory]
# Default directory: ./shoebox next to this script.
#
# The shoebox is deterministic: the same seven
# invented photographs with the same metadata
# every time. The pictures are minimal JPEGs
# synthesised for the lab (flat colours, no real
# scene); the metadata is the specimen. Names,
# people, places, and dates are invented, and
# the GPS coordinates point at public places,
# never at anyone's home.
#
# The tags are written with ExifTool itself, so
# ExifTool must already be installed (chapter 1
# covers that). Set EXIFTOOL to its path if it is
# not on your PATH.
#
# Running it again deletes and rebuilds the
# shoebox from scratch. It only ever touches the
# one directory named on its command line.

set -eu
dir=${1:-shoebox}
fail() { printf '%s\n' "refusing fixture target: $*" >&2; exit 1; }
# Resolve the existing parent, never follow a target symlink, and require an
# ownership marker before replacing any existing directory.
case $dir in ''|/|.|..|*/.|*/..) fail "$dir" ;; esac
dir=${dir%/}
[ ! -L "$dir" ] || fail "symlink $dir"
parent=$(cd -- "$(dirname -- "$dir")" && pwd -P) || exit 1
name=$(basename -- "$dir")
case $name in ''|.|..) fail "$dir" ;; esac
dir="$parent/$name"
script_dir=$(cd -- "$(dirname -- "$0")" && pwd -P) || exit 1
cwd=$(pwd -P)
home=$(cd -- "$HOME" && pwd -P) || exit 1
for protected in "$cwd" "$script_dir" "$home"; do
  case "$protected/" in "$dir/"*) fail "protected directory $dir" ;; esac
done
marker="$dir.mere-mortals-fixture"
if [ -e "$dir" ]; then
  [ -d "$dir" ] && [ ! -L "$marker" ] && [ -f "$marker" ] || fail "existing unowned target $dir"
  [ "$(cat -- "$marker")" = "exiftool-for-mere-mortals:v1" ] || fail "wrong ownership marker in $dir"
fi
# Refuse overlapping builders. A failed build leaves an unowned directory,
# which must be inspected manually rather than removed on the next run.
lock="$dir.build-lock"
mkdir -- "$lock" 2>/dev/null || fail "build already active (or stale lock): $lock"
trap 'rmdir -- "$lock"' EXIT
trap 'exit 1' HUP INT TERM
# The marker certifies a completed build only: clear it before rebuilding,
# so an interrupted build leaves an unmarked tree the next run refuses.
rm -f -- "$marker"
[ ! -e "$dir" ] || rm -rf -- "$dir"
mkdir -p "$dir"

EXIFTOOL=${EXIFTOOL:-exiftool}
command -v "$EXIFTOOL" >/dev/null 2>&1 || {
  echo "build-shoebox: ExifTool not found (set EXIFTOOL=/path/to/exiftool)" >&2; exit 1; }

# The seven pictures: tiny synthesised JPEGs, decoded from base64 so this
# script carries them without binary files in the repo.
decode_jpeg() {
  if base64 -d >/dev/null 2>&1 </dev/null; then
    base64 -d > "$dir/$1"
  else
    perl -MMIME::Base64 -e 'local $/; print decode_base64(<STDIN>)' > "$dir/$1"
  fi
}

